"""Backlink Toxicity Scanner & Google Disavow Generator.

Scans inbound backlinks for spam TLDs, betting/casino anchors,
and unnatural patterns. Generates standard Google Disavow-formatted exports.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Tuple

from backlink_agent.models import BacklinkRecord, LinkStatus

SPAM_TLDS = [".xyz", ".top", ".click", ".buzz", ".win", ".bid", ".loan", ".racing", ".date"]
SPAM_ANCHOR_PATTERNS = [
    r"\bcasino\b", r"\bbetting\b", r"\bslot[s]?\b", r"\bpoker\b",
    r"\bviagra\b", r"\bcialis\b", r"\bpayday loan\b", r"\bcrypto doubler\b"
]


class ToxicityScanner:
    """Analyzes backlink records and detects toxic spam injections."""

    def evaluate_link(self, record: BacklinkRecord) -> Tuple[float, List[str]]:
        """Calculate toxicity score (0-100) and identify risk signals."""
        score = 0.0
        flags: List[str] = []
        source_lower = record.source_url.lower()
        anchor_lower = record.anchor_text.lower()

        # 1. Spam TLD Check
        for tld in SPAM_TLDS:
            if tld in source_lower:
                score += 45.0
                flags.append(f"Spam TLD detected: {tld}")
                break

        # 2. Gambling / Pharma Anchor Check
        for pat in SPAM_ANCHOR_PATTERNS:
            if re.search(pat, anchor_lower):
                score += 50.0
                flags.append(f"Toxic anchor pattern matched: {pat}")
                break

        # 3. Domain authority check
        if record.domain_authority is not None and record.domain_authority < 5.0:
            score += 15.0
            flags.append("Extremely low domain authority (<5)")

        final_score = min(score, 100.0)
        return final_score, flags

    def audit_inventory(self, records: List[BacklinkRecord]) -> Dict[str, Any]:
        """Audit full link profile and identify candidates for disavow."""
        clean_links: List[BacklinkRecord] = []
        toxic_links: List[BacklinkRecord] = []

        for r in records:
            tox_score, flags = self.evaluate_link(r)
            r.toxicity_score = tox_score
            if tox_score >= 50.0:
                r.status = LinkStatus.TOXIC
                toxic_links.append(r)
            else:
                clean_links.append(r)

        return {
            "total_links": len(records),
            "clean_links_count": len(clean_links),
            "toxic_links_count": len(toxic_links),
            "overall_toxicity_rate_pct": round((len(toxic_links) / len(records) * 100.0) if records else 0.0, 1),
            "toxic_links": [r.to_dict() for r in toxic_links],
        }

    def generate_disavow_file(self, toxic_records: List[BacklinkRecord]) -> str:
        """Generate Google Search Console-compatible disavow.txt content."""
        lines = [
            "# Google Search Console Disavow File for aitoolgems.tech",
            "# Generated by HERMES Backlink Intelligence Agent (AGENT-10)",
            f"# Total entries: {len(toxic_records)}",
            "",
        ]
        disavowed_domains = set()
        for r in toxic_records:
            match = re.search(r"https?://([^/]+)", r.source_url)
            if match:
                domain = match.group(1).lower()
                if domain not in disavowed_domains:
                    lines.append(f"domain:{domain}")
                    disavowed_domains.add(domain)

        return "\n".join(lines)
